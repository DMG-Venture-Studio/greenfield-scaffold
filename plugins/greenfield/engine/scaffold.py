"""Generate a greenfield project from a confirmed intake: deterministic, no judgment, refuses to overwrite.

    python3 scaffold.py --intake intake.json --dest ~/Dev/billing [--doc brief.md]... [--dry-run] [--git]

Exit codes: 0 done; 2 bad arguments or environment; 3 the intake breaks a convention (every problem listed);
4 the destination holds files; 5 a git step failed (the files are written; the message says which step).
"""

from __future__ import annotations

import sys

if sys.version_info < (3, 12):  # noqa: UP036  # before the imports that need 3.12, so the message is readable
    sys.stderr.write("scaffold: needs Python 3.12 or later; run it with `uv run --python 3.12 python ...`\n")
    raise SystemExit(2)

import argparse
import importlib.util
import json
import re
import shutil
import subprocess
import tempfile
import tomllib
from pathlib import Path
from types import ModuleType

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import backend  # noqa: E402
import bootstrap  # noqa: E402
import docs  # noqa: E402
import harness  # noqa: E402
import kits  # noqa: E402
import plants  # noqa: E402
import spec  # noqa: E402
import web  # noqa: E402
from intake import IntakeError, Project, load  # noqa: E402

VERSION = "0.1.0"
TOOLKIT = HERE / "toolkit"
IGNORABLE = {".git", ".DS_Store"}


def _renderer() -> ModuleType:
    """The toolkit's contracts renderer, loaded from the copy that ships into the project."""
    path = TOOLKIT / "render_import_contracts.py"
    module_spec = importlib.util.spec_from_file_location("render_import_contracts", path)
    if module_spec is None or module_spec.loader is None:
        raise SystemExit(f"scaffold: cannot load {path}")
    module = importlib.util.module_from_spec(module_spec)
    module_spec.loader.exec_module(module)
    return module


def _slugify(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-") or "brief"


RESERVED_BRIEFS = ("bootstrap-prompt", "intake", "architecture")


def brief_names(date: str, doc_paths: list[Path]) -> tuple[list[str], list[str]]:
    """The file name each brief gets under the decision sources, and every clash that would lose one."""
    names = [f"{date}-{_slugify(doc.stem)}{doc.suffix or '.md'}" for doc in doc_paths]
    clashes = [
        f"{doc} would be filed as the scaffold's own {name}"
        for doc, name in zip(doc_paths, names, strict=True)
        if _slugify(doc.stem) in RESERVED_BRIEFS or _slugify(doc.stem).startswith("scoping-")
    ]
    clashes += [
        f"{doc} and another brief would both be filed as {name}"
        for doc, name in zip(doc_paths, names, strict=True)
        if names.count(name) > 1
    ]
    return names, clashes


def build(p: Project, intake_path: Path, doc_paths: list[Path], stage: Path) -> list[str]:
    """Write the whole project into stage; return the paths of the briefs dropped in."""
    briefs, _ = brief_names(p.date, doc_paths)
    out: dict[str, str] = {"project-spec.toml": spec.render(p)}
    out |= backend.files(p) | web.files(p) | docs.files(p, briefs) | harness.files(p) | kits.files(p)
    out["plants.toml"] = plants.render(p)
    for name in (
        "render_import_contracts.py",
        "prove_checks.py",
        "harness_audit.py",
        "harness_issues.py",
        "credentials.py",
    ):
        out[f"tools/toolkit/{name}"] = (TOOLKIT / name).read_text()
    out["tools/toolkit/README.md"] = (TOOLKIT / "README.md").read_text().replace("{{version}}", VERSION)
    out["tools/toolkit/VERSION"] = f"{VERSION}\n"
    out[f"docs/decisions/sources/{p.date}-bootstrap-prompt.md"] = bootstrap.render(p, VERSION, briefs)
    out[f"docs/decisions/sources/{p.date}-intake.json"] = intake_path.read_text()
    for path, text in out.items():
        target = stage / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text)
    for doc, name in zip(doc_paths, briefs, strict=True):
        shutil.copyfile(doc, stage / "docs" / "decisions" / "sources" / name)
    parsed = tomllib.loads((stage / "project-spec.toml").read_text())
    (stage / "contracts.toml").write_text(_renderer().render(parsed, stage / "src" / p.package))
    return briefs


def _tree(stage: Path) -> list[str]:
    return sorted(str(path.relative_to(stage)) for path in stage.rglob("*") if path.is_file())


def _git(dest: Path, p: Project) -> str | None:
    """Initialise, commit and link the remote; return the failing step, or None."""
    org, name = p.repo.get("org"), p.repo.get("name", p.slug)
    steps = [
        ["git", "init", "-q", "-b", "main"],
        ["git", "add", "-A"],
        [
            "git",
            "commit",
            "-q",
            "-m",
            f"Scaffold {p.name}",
            "-m",
            f"Generated by greenfield {VERSION} from docs/decisions/sources/{p.date}-intake.json.",
        ],
    ]
    if org and p.repo.get("remote") != "none":
        steps.append(["git", "remote", "add", "origin", f"https://github.com/{org}/{name}.git"])
    for step in steps:
        result = subprocess.run(step, cwd=dest, capture_output=True, text=True, check=False)
        if result.returncode:
            return f"{' '.join(step[:3])}: {(result.stderr or result.stdout).strip()}"
    return None


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description="Scaffold a greenfield project from a confirmed intake.")
    parser.add_argument("--intake", type=Path, required=True)
    parser.add_argument("--dest", type=Path, required=True)
    parser.add_argument("--doc", type=Path, action="append", default=[])
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--git", action="store_true", help="git init, commit, and add the remote")
    args = parser.parse_args(argv)
    missing = [str(d) for d in args.doc if not d.is_file()]
    if missing:
        sys.stderr.write(f"scaffold: these docs do not exist: {', '.join(missing)}\n")
        return 2
    try:
        project = load(args.intake)
    except IntakeError as problems:
        sys.stderr.write(f"scaffold: the intake breaks these conventions, so nothing was written:\n{problems}\n")
        return 3
    _, clashes = brief_names(project.date, args.doc)
    if clashes:
        sys.stderr.write(
            "scaffold: rename these briefs, so nothing was written:\n" + "".join(f"- {c}\n" for c in clashes)
        )
        return 2
    dest = args.dest.expanduser().resolve()
    present = [p.name for p in dest.iterdir()] if dest.is_dir() else []
    if [name for name in present if name not in IGNORABLE]:
        sys.stderr.write(
            f"scaffold: {dest} already holds files; a greenfield scaffold writes only into an empty folder\n"
        )
        return 4
    with tempfile.TemporaryDirectory() as tmp:
        stage = Path(tmp)
        build(project, args.intake, args.doc, stage)
        tree = _tree(stage)
        if args.dry_run:
            counts = {
                name: (stage / name).read_text().count("[[plant]]")
                for name in ("plants.toml", "web/plants.toml")
                if (stage / name).exists()
            }
            print(json.dumps({"dest": str(dest), "plants": counts, "files": tree}, indent=1))
            return 0
        dest.mkdir(parents=True, exist_ok=True)
        shutil.copytree(stage, dest, dirs_exist_ok=True)
    print(f"wrote {len(tree)} files to {dest}")
    if args.git:
        failed = _git(dest, project)
        if failed:
            sys.stderr.write(f"scaffold: the files are written, but a git step failed: {failed}\n")
            return 5
        linked = project.repo.get("org") and project.repo.get("remote") != "none"
        print("git: initialised, committed" + (", origin added" if linked else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
